-- Auto-updates updated_at on any row change (replaces MySQL's ON UPDATE CURRENT_TIMESTAMP).
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE users (
    user_id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name              VARCHAR(50)  NOT NULL,
    last_name               VARCHAR(50)  NOT NULL,
    date_of_birth           DATE,
    email                   VARCHAR(255) NOT NULL,
    role                    VARCHAR(20)  NOT NULL DEFAULT 'student',
    institution             VARCHAR(150),
    theme_mode              VARCHAR(20)  NOT NULL DEFAULT 'light',
    preferred_gpa_scale     NUMERIC(3,1) NOT NULL DEFAULT 12.0,
    default_reminder_days   INTEGER      NOT NULL DEFAULT 3,
    default_reminder_method VARCHAR(20)  NOT NULL DEFAULT 'email',
    password_hash           VARCHAR(255) NOT NULL,
    gpa                     NUMERIC(4,2),
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_role CHECK (role IN ('student', 'admin')),
    CONSTRAINT chk_users_theme CHECK (theme_mode IN ('light', 'dark')),
    CONSTRAINT chk_users_gpa_scale CHECK (preferred_gpa_scale IN (4.0, 12.0)),
    CONSTRAINT chk_users_default_reminder_days CHECK (default_reminder_days >= 0 AND default_reminder_days <= 365),
    CONSTRAINT chk_users_default_reminder_method CHECK (default_reminder_method IN ('email', 'whatsapp')),
    CONSTRAINT chk_users_gpa CHECK (gpa IS NULL OR (gpa >= 0.00 AND gpa <= 12.00))
);
CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE courses (
    course_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        INTEGER      NOT NULL,
    course_code    VARCHAR(20)  NOT NULL,
    course_name    VARCHAR(150) NOT NULL,
    professor_name VARCHAR(100),
    term           VARCHAR(30)  NOT NULL,
    term_end       DATE,
    office_hours   VARCHAR(255),
    meeting_times  VARCHAR(255),
    room           VARCHAR(80),
    textbook_link  VARCHAR(500),
    gpa_goal       NUMERIC(4,2),
    archived       BOOLEAN      NOT NULL DEFAULT FALSE,
    final_grade    NUMERIC(5,2),
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_courses_user_code_term UNIQUE (user_id, course_code, term),
    CONSTRAINT chk_courses_gpa_goal CHECK (gpa_goal IS NULL OR (gpa_goal >= 0.00 AND gpa_goal <= 12.00)),
    CONSTRAINT chk_courses_final_grade CHECK (final_grade IS NULL OR (final_grade >= 0.00 AND final_grade <= 100.00)),
    CONSTRAINT fk_courses_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TRIGGER trg_courses_updated_at BEFORE UPDATE ON courses
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE activity_categories (
    activity_category_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    activity_category_name VARCHAR(50) NOT NULL,
    created_at             TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_activity_categories_name UNIQUE (activity_category_name)
);

CREATE TABLE activities (
    activity_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id            INTEGER      NOT NULL,
    activity_category_id INTEGER      NOT NULL,
    activity_name        VARCHAR(150) NOT NULL,
    due_date             TIMESTAMP    NOT NULL,
    grading_weight       NUMERIC(5,2) NOT NULL DEFAULT 0.00,
    reminder_date        TIMESTAMP,
    reminder_method      VARCHAR(20)  NOT NULL DEFAULT 'email',
    reminder_sent        BOOLEAN      NOT NULL DEFAULT FALSE,
    priority_level       VARCHAR(20)  NOT NULL DEFAULT 'medium',
    grade                NUMERIC(5,2),
    status               VARCHAR(20)  NOT NULL DEFAULT 'not_started',
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_activities_course_name_due UNIQUE (course_id, activity_name, due_date),
    CONSTRAINT chk_activities_weight CHECK (grading_weight >= 0.00 AND grading_weight <= 100.00),
    CONSTRAINT chk_activities_reminder_date CHECK (reminder_date IS NULL OR reminder_date <= due_date),
    CONSTRAINT chk_activities_reminder_method CHECK (reminder_method IN ('email', 'whatsapp')),
    CONSTRAINT chk_activities_priority CHECK (priority_level IN ('low', 'medium', 'high')),
    CONSTRAINT chk_activities_grade CHECK (grade IS NULL OR (grade >= 0.00 AND grade <= 100.00)),
    CONSTRAINT chk_activities_status CHECK (status IN ('not_started', 'in_progress', 'submitted', 'graded')),
    CONSTRAINT fk_activities_course FOREIGN KEY (course_id)
        REFERENCES courses (course_id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_activities_category FOREIGN KEY (activity_category_id)
        REFERENCES activity_categories (activity_category_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TRIGGER trg_activities_updated_at BEFORE UPDATE ON activities
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE password_reset_tokens (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    INTEGER,
    token      VARCHAR(130) NOT NULL,
    expires_at TIMESTAMP,
    CONSTRAINT uq_password_reset_user UNIQUE (user_id),
    CONSTRAINT fk_password_reset_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE INDEX idx_courses_user_id ON courses (user_id);
CREATE INDEX idx_courses_user_archived ON courses (user_id, archived);
CREATE INDEX idx_activities_course_id ON activities (course_id);
CREATE INDEX idx_activities_category_id ON activities (activity_category_id);
CREATE INDEX idx_activities_due_date ON activities (due_date);
CREATE INDEX idx_activities_reminder_due ON activities (reminder_sent, reminder_date);

